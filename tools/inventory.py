#!/usr/bin/env python3
"""Regenerate INVENTORY.md and MANIFEST.json by scanning this machine.

Nothing is remembered; everything is read. Run it after any install or config change:

    python3 tools/inventory.py
"""

import json
import pathlib
import re
import sqlite3
import subprocess
import sys

HOME = pathlib.Path.home()
CFG = HOME / ".config" / "opencode"
FREELMAPI_DB = HOME / "Default Project" / "freellmapi" / "server" / "data" / "freeapi.db"
OUT_MD = pathlib.Path(__file__).resolve().parent.parent / "INVENTORY.md"
OUT_JSON = pathlib.Path(__file__).resolve().parent.parent / "MANIFEST.json"


def run(*cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=10).stdout.strip()
    except Exception:
        return ""


def frontmatter(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    out = {}
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            for line in text[3:end].splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    out[k.strip().lower()] = v.strip().strip('"\'')
    return out, text


def scan_agents():
    items = []
    for p in sorted((CFG / "agents").glob("*.md")):
        meta, _ = frontmatter(p)
        items.append({
            "id": p.stem,
            "name": meta.get("name", p.stem),
            "description": (meta.get("description") or "")[:150],
            "mode": meta.get("mode", ""),
        })
    return items


def scan_skills():
    items = []
    for d in sorted((CFG / "skills").iterdir()) if (CFG / "skills").is_dir() else []:
        if not d.is_dir():
            continue
        md = d / "SKILL.md"
        desc = ""
        if md.exists():
            meta, _ = frontmatter(md)
            desc = (meta.get("description") or "")[:120]
        items.append({"id": d.name, "description": desc})
    return items


def scan_commands():
    return [{"id": p.stem} for p in sorted((CFG / "commands").glob("*.md"))]


def scan_plugins():
    d = CFG / "plugins"
    return sorted(p.name for p in d.iterdir()) if d.is_dir() else []


def scan_providers():
    if not FREELMAPI_DB.exists():
        return [], {}
    con = sqlite3.connect(FREELMAPI_DB)
    keys = [{"platform": p, "status": s, "enabled": bool(e)}
            for p, s, e in con.execute("select platform,status,enabled from api_keys order by id")]
    counts = {
        "models": con.execute("select count(*) from models").fetchone()[0],
        "platforms": con.execute("select count(distinct platform) from models").fetchone()[0],
    }
    return keys, counts


def ecc_version():
    pkg = CFG / "package.json"
    if not pkg.exists():
        return "unknown"
    d = json.loads(pkg.read_text())
    return f"{d.get('name','?')} {d.get('version','?')}"


def main():
    agents = scan_agents()
    skills = scan_skills()
    commands = scan_commands()
    plugins = scan_plugins()
    providers, counts = scan_providers()

    manifest = {
        "generated_by": "tools/inventory.py",
        "host": {
            "cpu": run("sh", "-c", "grep -m1 'model name' /proc/cpuinfo | cut -d: -f2").strip(),
            "threads": int(run("nproc") or 0),
            "node": run("node", "-v"),
            "git": run("git", "--version"),
            "python": run("python3", "-V"),
        },
        "ecc": ecc_version(),
        "counts": {
            "agents": len(agents), "skills": len(skills),
            "commands": len(commands), "plugins": len(plugins),
        },
        "providers": providers,
        "catalog": counts,
        "agents": agents,
        "skills": skills,
        "commands": commands,
        "plugins": plugins,
    }
    OUT_JSON.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    L = ["# Inventory", "",
         f"Generated by `tools/inventory.py` on {run('date', '+%Y-%m-%d')}. "
         "Regenerate rather than edit by hand.", "",
         "## Host", "",
         f"- CPU: {manifest['host']['cpu'].strip() or 'unknown'} ({manifest['host']['threads']} threads)",
         f"- Node: {manifest['host']['node']}",
         f"- Git: {manifest['host']['git']}",
         f"- Python: {manifest['host']['python']}",
         "", "## Installed", "",
         f"- ECC: `{manifest['ecc']}`",
         f"- Agents: **{len(agents)}** (markdown) ",
         f"- Skills: **{len(skills)}**",
         f"- Commands: **{len(commands)}**",
         f"- Plugins: {len(plugins)} — {', '.join(f'`{p}`' for p in plugins)}",
         "", "## Inference", "",
         f"- Router catalog: **{counts.get('models','?')} models / {counts.get('platforms','?')} platforms**",
         "", "| Provider | Status | Enabled |", "|---|---|---|"]
    for p in providers:
        L.append(f"| {p['platform']} | {p['status']} | {'yes' if p['enabled'] else 'no'} |")

    L += ["", "## Commands", "", " ".join(f"`/{c['id']}`" for c in commands), "",
          "## Skills", "", "| Skill | Description |", "|---|---|"]
    for s in skills:
        L.append(f"| `{s['id']}` | {s['description']} |")

    L += ["", "## Agents", "", "| Agent | Description |", "|---|---|"]
    for a in agents:
        L.append(f"| `{a['id']}` | {a['description']} |")

    OUT_MD.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT_MD.name} ({len(L)} lines) and {OUT_JSON.name}")
    print(f"agents={len(agents)} skills={len(skills)} commands={len(commands)} providers={len(providers)}")


if __name__ == "__main__":
    sys.exit(main())
